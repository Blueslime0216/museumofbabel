// 후원자 — 로비에 자기 그림을 걸어 둔 사람들
//
// ── 사진을 받지 않는다. 주소를 받는다 ────────────────────────────────────
//
// 후원자가 고른 그림은 **좌표로만** 저장한다. 파일을 호스팅하면 "픽셀은
// 브라우저가 계산한다. 이미지를 가져오지 않는다"가 깨진다. 그 약속이 이 미술관의
// 중심 주장이므로, 로비에서만 예외를 두지 않는다.
//
// 자기 사진을 걸고 싶은 사람은 찾기의 그림 올리기로 가장 닮은 좌표를 찾고, 그
// 주소를 준다. 투영은 손실이지만 알아볼 수 있다 — 로고와 사진으로 확인했다.
//
// ── 이 목록은 가져와야 하는 데이터다 ─────────────────────────────────────
//
// 미술관의 내용이 순수하게 코드만의 함수라는 성질에 이것만 예외다. 후원자 이름은
// 계산될 수 없기 때문이다. 로비가 작품 공간 **밖**이므로 그 예외는 로비 안에
// 갇힌다. 작품 층은 여전히 코드만의 함수다.
//
// ── 형식 ─────────────────────────────────────────────────────────────────
//
//   name     이름표에 그대로 적는다. 번역하지 않는다 — 사람 이름이다
//   address  { tier, locality, x, y }. x·y 는 BigInt 다
//   at       로비 안의 자리 { x, y }. 생략하면 날짜 시드로 자동 배치한다
//
// 자리를 적으면 그 사람의 그림이 늘 같은 곳에 걸린다. 적지 않으면 오늘의 그림과
// 같은 규칙으로 흩어진다. 오래 후원한 사람에게 좋은 자리를 주고 싶을 때 쓴다.

