// 여덟 방향 건너뛰기
//
// 고른 그림 뒤에서 여덟 개의 단추가 나오고, 누르면 그 방향으로 1,000걸음 간
// 자리로 옮긴다.
//
// ── 왜 1,000인가 ────────────────────────────────────────────────────────
//
// 화면에 3~7칸이 보인다. 방향키로 한 칸씩 걸으면 1,000칸은 도달할 수 없는
// 거리이고, 전시실 하나가 160칸 간격의 씨앗으로 나뉘므로 1,000칸은 방 여섯 개쯤을
// 지나는 거리다. 곧 **다른 방에서 깨어나는** 거리다.
//
// 무작위 점프(r 키)와 다른 점이 여기 있다. 무작위는 어디로 갈지 모르고, 이것은
// 방향을 고른다. "저쪽으로 한참 가 보자" 가 가능해진다.
//
// ── 대각선은 두 축 모두 1,000이다 ────────────────────────────────────────
//
// 707칸씩(1,000의 √2분의 1) 갈 수도 있었다. 그러면 여덟 방향의 이동 거리가 모두
// 같아진다. 그렇게 하지 않았다 — 좌표는 두 축의 값이고, 사람이 기억하는 것은
// "오른쪽으로 1,000, 아래로 1,000" 이다. 화면에 보이는 거리를 맞추는 것보다
// 좌표를 맞추는 것이 이 미술관의 셈에 가깝다.

/**
 * 여덟 방향. 이름은 i18n 열쇠와 화살표를 함께 정한다.
 *
 * 순서가 화면의 순서다(위에서 시계 방향). 나오는 시차를 이 순서로 준다.
 */
export const JUMP_DIRECTIONS = [
  { id: 'up', dx: 0, dy: -1, arrow: '↑' },
  { id: 'upRight', dx: 1, dy: -1, arrow: '↗' },
  { id: 'right', dx: 1, dy: 0, arrow: '→' },
  { id: 'downRight', dx: 1, dy: 1, arrow: '↘' },
  { id: 'down', dx: 0, dy: 1, arrow: '↓' },
  { id: 'downLeft', dx: -1, dy: 1, arrow: '↙' },
  { id: 'left', dx: -1, dy: 0, arrow: '←' },
  { id: 'upLeft', dx: -1, dy: -1, arrow: '↖' },
];

/** 한 번에 건너뛰는 걸음 수. */
export const JUMP_STEPS = 1000n;

/**
 * 그 방향으로 건너뛴 좌표.
 *
 * 축 크기로 감긴다. 층은 순환하므로 경계에서 튕겨 나갈 일이 없고, 감기지 않으면
 * 음수 좌표가 만들어져 주소가 깨진다.
 */
export function jumpTarget({ x, y }, direction, axisBits, steps = JUMP_STEPS) {
  const mask = (1n << BigInt(axisBits)) - 1n;
  const walk = BigInt(steps);
  return {
    x: (x + BigInt(direction.dx) * walk) & mask,
    y: (y + BigInt(direction.dy) * walk) & mask,
  };
}
